// Helper functions for bank querying and quiz generation
export function getQuestionsByDifficulty(difficulty: QuestionDifficulty): BibleQuestion[] {
  return BIBLE_QUESTION_BANK.filter((q) => q.difficulty === difficulty && q.reviewStatus !== 'retired');
}

export function getQuestionsByCategory(category: QuizCategory): BibleQuestion[] {
  return BIBLE_QUESTION_BANK.filter((q) => q.category === category && q.reviewStatus !== 'retired');
}

export function getQuestionsByTranslation(translationId: string): BibleQuestion[] {
  if (translationId === 'All') return BIBLE_QUESTION_BANK.filter((q) => q.reviewStatus !== 'retired');
  return BIBLE_QUESTION_BANK.filter(
    (q) => (q.translationId === translationId || q.translationId === 'Multi-Translation') && q.reviewStatus !== 'retired'
  );
}

export function getQuestionCountsByDifficulty(): Record<QuestionDifficulty, { total: number; approved: number; needsReview: number }> {
  const counts: Record<QuestionDifficulty, { total: number; approved: number; needsReview: number }> = {
    beginner: { total: 0, approved: 0, needsReview: 0 },
    developing: { total: 0, approved: 0, needsReview: 0 },
    intermediate: { total: 0, approved: 0, needsReview: 0 },
    advanced: { total: 0, approved: 0, needsReview: 0 },
    expert: { total: 0, approved: 0, needsReview: 0 },
  };

  for (const q of BIBLE_QUESTION_BANK) {
    if (counts[q.difficulty]) {
      counts[q.difficulty].total += 1;
      if (q.reviewStatus === 'approved') counts[q.difficulty].approved += 1;
      if (q.reviewStatus === 'needs_review') counts[q.difficulty].needsReview += 1;
    }
  }

  return counts;
}

export function generateLearningPathQuestions(levelNumber: number): BibleQuestion[] {
  const levelConfig = LEARNING_PATH_LEVELS.find((l) => l.level === levelNumber) || LEARNING_PATH_LEVELS[0];
  const pool = getQuestionsByDifficulty(levelConfig.difficulty);
  return pool.slice(0, levelConfig.questionCount);
}

export function generateProgressionCompetitionQuestions(): BibleQuestion[] {
  // Balanced 10-question sequence: 2 beginner -> 2 developing -> 2 intermediate -> 2 advanced -> 2 expert
  const b = getQuestionsByDifficulty('beginner').slice(0, 2);
  const d = getQuestionsByDifficulty('developing').slice(0, 2);
  const i = getQuestionsByDifficulty('intermediate').slice(0, 2);
  const a = getQuestionsByDifficulty('advanced').slice(0, 2);
  const e = getQuestionsByDifficulty('expert').slice(0, 2);
  return [...b, ...d, ...i, ...a, ...e];
}
